#!/bin/zsh
source ${0:A:h}/lib.sh
check "/ prerendered home" 200 "Welcome|astro" "$H/?$(t)"
check "/index.html" 200 "Welcome|astro" "$H/index.html?$(t)"
check "/about" 200 "<h1>About" "$H/about?$(t)"
check "/about/" 200 "<h1>About" "$H/about/?$(t)"
check "/about.html" 200 "<h1>About" "$H/about.html?$(t)"
check "/about revalidate" 200 "max-age=0, must-revalidate" "$H/about?$(t)"
check "/blog/a dynamic" 200 "Blog post a" "$H/blog/a?$(t)"
check "/blog/a/" 200 "Blog post a" "$H/blog/a/?$(t)"
check "/blog/a whole file" 200 "content-length: 35" "$H/blog/a?$(t)"
check "/posts index route" 200 "Posts:" "$H/posts?$(t)"
check "/posts/ index route" 200 "Posts:" "$H/posts/?$(t)"
check "/v1.2 dot in name" 200 "Version 1.2" "$H/v1.2?$(t)"
check "/api/static-data endpoint" 200 "static endpoint data" "$H/api/static-data?$(t)"
check "/feed.xml endpoint" 200 "<rss|<feed|xml" "$H/feed.xml?$(t)"
check "/nl/about i18n fallback" 200 "Redirecting to: /about" "$H/nl/about?$(t)"
check "/old redirect" 301 "location: .*/about" "$H/old?$(t)"
check "/old-blog/a redirect" 301 "location: .*/blog/a" "$H/old-blog/a?$(t)"
check "/CNAME" 200 "example.com" "$H/CNAME?$(t)"
check "/_headers" 200 "" "$H/_headers?$(t)"
check "/late-root.txt" 200 "written after" "$H/late-root.txt?$(t)"
check "/docs/late.txt storage first" 200 "written after" "$H/docs/late.txt?$(t)"
check "/favicon.svg" 200 "max-age=0, must-revalidate" "$H/favicon.svg?$(t)"
check "/_astro immutable" 200 "immutable" "$H/_astro/$(ls $WORK/$1/dist/client/_astro | grep -m1 '\.css$\|\.svg$')"
check "/missing" 404 "Custom 404" "$H/missing?$(t)"
check "/missing/" 404 "Custom 404" "$H/missing/?$(t)"
check "/blog/c not generated" 404 "Custom 404" "$H/blog/c?$(t)"
check "HEAD /about" 200 "" -I "$H/about?$(t)"
check "POST /about prerendered" 405 "allow: GET, HEAD" -X POST -d x=1 "$H/about?$(t)"
check "POST /CNAME file" 405 "allow: GET, HEAD" -X POST -d x=1 "$H/CNAME?$(t)"
check "POST /missing" 404 "Custom 404" -X POST -H "origin: $H" -d x=1 "$H/missing?$(t)"
check "on-demand product" 200 "Product 42" "$H/products/42?$(t)"
check "on-demand api" 200 "" "$H/api/time.json?$(t)"
report "format $1"
