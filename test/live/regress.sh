#!/bin/zsh
source ${0:A:h}/lib.sh
check "on-demand /" 200 "" "$H/?$(t)"
check "dynamic route" 200 "Product 42" "$H/products/42?$(t)"
check "catch-all" 200 "Docs: intro" "$H/docs/intro?$(t)"
check "endpoint json" 200 '"now"' "$H/api/time.json?$(t)"
check "waitUntil available" 200 '"waitUntil":"function"' "$H/api/wait-until.json?$(t)"
check "prerendered page" 200 "<h1>About" "$H/about?$(t)"
check "prerendered trailing slash" 200 "<h1>About" "$H/about/?$(t)"
check "prerendered dynamic" 200 "Blog post a" "$H/blog/a?$(t)"
check "prerendered endpoint" 200 "<rss" "$H/feed.xml?$(t)"
check "public file" 200 "<svg" "$H/favicon.svg?$(t)"
check "webmanifest type" 200 "content-type: application/manifest\+json" "$H/site.webmanifest?$(t)"
check "asset immutable" 200 "max-age=31536000, immutable" "$H/_astro/pixel.5vcyeoBI_Z2l5iAd.webp?$(t)"
check "public file revalidate" 200 "max-age=0, must-revalidate" "$H/favicon.svg?$(t)"
check "public under catch-all" 200 "Guide from public" "$H/docs/guide.txt?$(t)"
check "dot folder file" 200 "Contact" "$H/.well-known/security.txt?$(t)"
check "missing 404 page" 404 "Custom 404" "$H/missing?$(t)"
check "prerendered dynamic not built" 404 "Custom 404" "$H/blog/c?$(t)"
check "500 page" 500 "Custom 500" "$H/throws?$(t)"
check "rendered private" 200 "private, no-store" "$H/products/42?$(t)"
check "own cache header" 200 "public, max-age=60" "$H/headers?$(t)"
check "middleware header" 200 "x-middleware: ran" "$H/headers?$(t)"
check "locals" 200 "Middleware says: hello" "$H/headers?$(t)"
check "cookie set" 200 "set-cookie: visits=1" "$H/cookies?$(t)"
check "cookie read" 200 "Visits: 6" -H "cookie: visits=5" "$H/cookies?$(t)"
check "secret" 200 "Secret is set" "$H/env?$(t)"
check "runtime process.env" 200 "process.env: from-script-variable" "$H/runtime-env?$(t)"
check "island page" 200 "server-islands" "$H/island?$(t)"
check "redirect to on-demand" 301 "location: .*/products/42" "$H/old-products/42?$(t)"
check "Astro.redirect" 301 "location: .*/about" "$H/go?$(t)"
check "endpoint redirect" 302 "location: .*/about" "$H/api/go?$(t)"
check "redirect to prerendered" 301 "location: .*/about" "$H/old?$(t)"
check "redirect to prerendered slash" 301 "location: .*/about" "$H/old/?$(t)"
check "redirect dynamic to prerendered" 301 "location: .*/blog/a" "$H/old-blog/a?$(t)"
check "redirect POST" 308 "location: .*/about" -X POST -H "origin: $H" -d m=1 "$H/old"
check "POST echo" 200 "received" -X POST -H "origin: $H" -d m=1 "$H/api/echo"
check "POST cross-site" 403 "" -X POST -H "origin: https://evil.example" -d m=1 "$H/api/echo"
# A pull zone the deploy makes forces SSL, so http never reaches the script there; without it, the script has to accept a POST over http.
if curl -s -o /dev/null -w '%{redirect_url}' "${H/https/http}/?$(t)" | grep -q '^https://'; then
  check "POST http forced to https" 301 "location: https://" -X POST -H "origin: ${H/https/http}" -d m=1 "${H/https/http}/api/echo"
else
  check "POST http" 200 "received" -X POST -H "origin: ${H/https/http}" -d m=1 "${H/https/http}/api/echo"
fi
check "POST on file" 405 "allow: GET, HEAD" -X POST -H "origin: $H" -d m=1 "$H/favicon.svg"
check "POST on prerendered page" 405 "allow: GET, HEAD" -X POST -H "origin: $H" -d m=1 "$H/about/"
check "POST missing" 404 "Custom 404" -X POST -H "origin: $H" -d m=1 "$H/missing"
check "HEAD page" 200 "" -I "$H/about?$(t)"
check "range" 206 "content-range: bytes 0-9/" -H "Range: bytes=0-9" "$H/_astro/pixel.5vcyeoBI_Z2l5iAd.webp?$(t)"
check "collection list" 200 "Posts: 2" "$H/posts?$(t)"
check "collection entry" 200 "First post" "$H/posts/first?$(t)"
check "action form" 200 "Hello bunny" -X POST -H "origin: $H" -d name=bunny "$H/actions?_action=greet"
check "action json" 200 "Hello bunny" -X POST -H "origin: $H" -d name=bunny "$H/_actions/greet"
check "i18n nl" 200 "Hallo, locale nl" "$H/nl?$(t)"
check "i18n fallback on-demand" 302 "" "$H/nl/products/42?$(t)"
check "preferredLocale" 200 "Preferred: nl" -H "accept-language: nl" "$H/locale?$(t)"
check "late file root" 200 "written after" "$H/late-root.txt?$(t)"
check "rewrite on-demand" 200 "Product 7" "$H/rewrite/to-product?$(t)"
check "rewrite 404" 404 "Custom 404" "$H/rewrite/to-404?$(t)"
check "injected route" 200 "injected route" "$H/injected?$(t)"
check "public env" 200 "server: server-at-build, client: client-default" "$H/public-env?$(t)"
check "request url https" 200 '"astroUrl":"https://' "$H/request.json?$(t)"
IP=$(curl -s -m 30 https://api.ipify.org)
check "clientAddress" 200 "\"clientAddress\":\"$IP\"" "$H/client-address.json?$(t)"
check "clientAddress spoofed" 200 "\"clientAddress\":\"$IP\"" -H "x-real-ip: 6.6.6.6" -H "x-forwarded-for: 7.7.7.7" "$H/client-address.json?$(t)"
check "clientAddress POST" 200 "\"clientAddress\":\"$IP\"" -X POST -H "origin: $H" -d m=1 "$H/client-address.json"
report regress
